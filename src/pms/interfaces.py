"""Explicit service interfaces behind :mod:`pms.runtime` (persistence, search, files, notifications, jobs).

The offline implementations exist today (SQLite :class:`pms.store.Store`, SQLite FTS5
:class:`pms.knowledge.KnowledgeIndex`, a local folder file store, the outbox notifier and the
SQLite analysis-job queue). Azure implementations (Cosmos DB containers ``cases``, ``signals``,
``records`` and a create-only ``audit`` chain, Blob Storage, Azure AI Search, Communication
Services) plug in behind the same interfaces in :mod:`pms.runtime` without touching call sites.

Application code depends on these protocols only; it never instantiates a concrete store or
index (that happens in :mod:`pms.runtime`).
"""
from __future__ import annotations

import datetime as _dt
from dataclasses import dataclass, field
from typing import Any, ContextManager, Iterable, Protocol, runtime_checkable

from .knowledge import SearchHit, SearchQuery
from .models import (
    AgentRun, Alert, Approval, Case, Clock, CorrelationRecord, CostRecord, DeadlineRow, Decision, Fact, Finding,
    MetadataEdit, Recommendation, Signal, Submission, Task,
)


# --------------------------------------------------------------------------- audit and case store
@runtime_checkable
class AuditTrail(Protocol):
    """Append-only, hash-chained audit trail (concept 8). There is no update or delete."""

    def append(self, *, event_type: str, source: str, actor_type: str, actor_id: str, case_id: str | None = None,
               signal_id: str | None = None, before: Any = None, after: Any = None, reason: str | None = None,
               rule_versions: Iterable[str] | None = None, agent_version: str | None = None,
               model: str | None = None, model_version: str | None = None, prompt_version: str | None = None,
               corpus_version: str | None = None, source_ids: Iterable[str] | None = None,
               usage: dict[str, Any] | None = None, cost_estimate: dict[str, Any] | None = None,
               ts: Any = None) -> dict[str, Any]: ...

    def records(self, *, case_id: str | None = None, event_type: str | None = None, after_seq: int = 0,
                limit: int | None = None) -> list[dict[str, Any]]: ...

    def count(self, *, case_id: str | None = None, event_type: str | None = None) -> int: ...

    def head(self) -> str: ...

    def verify(self) -> Any: ...  # pms.audit.VerifyResult (ok, checked, first_break_seq, reason, head_hash)


